// EnumDef describes a string enum exported to TypeScript generation.
type EnumDef struct {
	Name   string
	Values []string
}

func toStrings[T ~string](vals []T) []string {
	out := make([]string, len(vals))
	for i, v := range vals {
		out[i] = string(v)
	}
	return out
}

