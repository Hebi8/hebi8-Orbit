package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/Hebi8/hebi8-Orbit/internal/protocol"
)

func main() {
	outPath := flag.String("out", "web/src/generated/protocol.ts", "output path for generated TypeScript definitions")
	flag.Parse()

	src := generateTS()
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "mkdir failed: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outPath, []byte(src), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write failed: %v\n", err)
		os.Exit(1)
	}
}

func generateTS() string {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/gen-ts from internal/protocol. DO NOT EDIT.\n\n")

	enumNames := map[string]bool{}
	for _, e := range protocol.ExportedEnums() {
		enumNames[e.Name] = true
		quoted := make([]string, len(e.Values))
		for i, v := range e.Values {
			quoted[i] = fmt.Sprintf("%q", v)
		}
		fmt.Fprintf(&buf, "export const %sValues = [%s] as const;\n", e.Name, strings.Join(quoted, ", "))
		fmt.Fprintf(&buf, "export type %s = (typeof %sValues)[number];\n\n", e.Name, e.Name)
	}

	dtoNames := map[string]bool{}
	for _, t := range protocol.ExportedDTOTypes() {
		dtoNames[t.Name()] = true
	}

	for _, t := range protocol.ExportedDTOTypes() {
		fmt.Fprintf(&buf, "export interface %s {\n", t.Name())
		for i := range t.NumField() {
			f := t.Field(i)
			if !f.IsExported() {
				continue
			}
			tag := f.Tag.Get("json")
			if tag == "-" {
				continue
			}
			parts := strings.Split(tag, ",")
			name := parts[0]
			if name == "" {
				name = f.Name
			}
			optional := false
			for _, opt := range parts[1:] {
				if opt == "omitempty" {
					optional = true
				}
			}
			tsType := goTypeToTS(f.Type, enumNames, dtoNames)
			optMark := ""
			if optional {
				optMark = "?"
			}
			fmt.Fprintf(&buf, "  %s%s: %s;\n", name, optMark, tsType)
		}
		buf.WriteString("}\n\n")
	}

	return buf.String()
}

func goTypeToTS(t reflect.Type, enumNames, dtoNames map[string]bool) string {
	if t.Kind() == reflect.Pointer {
		inner := goTypeToTS(t.Elem(), enumNames, dtoNames)
		return inner + " | null"
	}
	if enumNames[t.Name()] || dtoNames[t.Name()] {
		return t.Name()
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		elem := goTypeToTS(t.Elem(), enumNames, dtoNames)
		if strings.Contains(elem, "|") {
			return "(" + elem + ")[]"
		}
		return elem + "[]"
	case reflect.Map:
		val := goTypeToTS(t.Elem(), enumNames, dtoNames)
		return fmt.Sprintf("Record<string, %s>", val)
	case reflect.Interface:
		return "unknown"
	default:
		return "unknown"
	}
}
